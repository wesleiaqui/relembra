test('Canvas demonstração fictícia contém quatro tipos, conexões e IDs únicos',()=>{
  const demo=exampleCanvas();
  assert.deepEqual(new Set(demo.nodes.map(n=>n.type)),new Set(['group','note','task','link']));
  assert.equal(demo.edges.length,2);
  const encoded=validateCanvas(demo);
  assert.equal(JSON.parse(encoded).nodes.length,4);
  assert.equal(JSON.parse(encoded).edges.length,2);
  assert.throws(()=>validateCanvas({...demo,edges:[{id:crypto.randomUUID(),from:demo.nodes[0].id,to:'invalid',label:''}]}),/Conexão inválida/);
});
test('Canvas não permite URL javascript, IDs duplicados ou posição infinita',()=>{
  const demo=exampleCanvas();
  const malicious=structuredClone(demo);
  malicious.nodes.find(n=>n.type==='link').url='javascript:alert(1)';
  assert.throws(()=>validateCanvas(malicious),/HTTP ou HTTPS/);
  const copy=structuredClone(demo);
  copy.nodes.push({...copy.nodes[1]});
  assert.throws(()=>validateCanvas(copy),/duplicado/);
  const moved=structuredClone(demo);
  moved.nodes[0].x=Infinity;
  assert.throws(()=>validateCanvas(moved),/Posição inválida/);
});
